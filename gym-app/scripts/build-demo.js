const backend = `// Generated by scripts/build-demo.js: the gym API running in the browser.
(function () {
  const SEED = ${fs.readFileSync(path.join(root, 'seed', 'gym.json'), 'utf8')};

  // Just enough of node:crypto for ids, tokens and demo PIN hashes.
  const hex = (bytes) => Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
  const wrap = (bytes) => ({ bytes, toString: () => hex(bytes) });
  function hashBytes(text, size) {
    const outBytes = new Uint8Array(size);
    let h1 = 0xdeadbeef;
    let h2 = 0x41c6ce57;
    for (let round = 0; round < size; round += 4) {
      for (let i = 0; i < text.length; i++) {
        const c = text.charCodeAt(i) + round;
        h1 = Math.imul(h1 ^ c, 2654435761);
        h2 = Math.imul(h2 ^ c, 1597334677);
      }
      h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
      for (let j = 0; j < 4 && round + j < size; j++) outBytes[round + j] = (h1 >>> (j * 8)) & 255;
    }
    return outBytes;
  }
  const cryptoShim = {
    randomBytes: (n) => wrap(crypto.getRandomValues(new Uint8Array(n))),
    randomInt: (min, max) => min + Math.floor(Math.random() * (max - min)),
    createHash: () => { let s = ''; return { update(x) { s += x; return this; }, digest: () => hex(hashBytes(s, 32)) }; },
    scryptSync: (pin, salt, size) => wrap(hashBytes(salt + ':' + pin, size)),
    timingSafeEqual: (a, b) => hex(a.bytes) === hex(b.bytes),
  };

  const sources = {
${Object.entries(modules).map(([name, src]) => `    ${JSON.stringify(name)}: function (module, exports, require) {\n${src}\n    },`).join('\n')}
  };
  const cache = {};
  function req(name) {
    if (name === 'node:crypto') return cryptoShim;
    if (cache[name]) return cache[name].exports;
    const module = { exports: {} };
    cache[name] = module;
    sources[name](module, module.exports, req);
    return module.exports;
  }

  let api = null;
  const realFetch = window.fetch.bind(window);
  window.fetch = async function (input, init = {}) {
    const url = new URL(String(input), 'http://demo.local');
    if (!url.pathname.startsWith('/api/')) return realFetch(input, init);
    if (!api) api = req('./api').createApi(req('./store').createStore({}));
    const headers = init.headers || {};
    const fakeReq = { method: init.method || 'GET', headers: { authorization: headers.Authorization || headers.authorization || '' }, socket: { remoteAddress: 'demo' } };
    let status = 200;
    let payload;
    try {
      const body = init.body ? JSON.parse(init.body) : {};
      payload = await api.handle(fakeReq, null, url, body);
    } catch (e) {
      status = e.status || 500;
      payload = { error: e.status ? e.message : 'Something went wrong' };
      if (!e.status) console.error(e);
    }
    return new Response(JSON.stringify(payload), { status, headers: { 'Content-Type': 'application/json' } });
  };
  window.resetGymDemo = () => { try { localStorage.removeItem('${'gymDemoDb'}'); } catch (e) { /* ignore */ } };
})();
`;
fs.writeFileSync(path.join(out, 'demo-backend.js'), backend);

