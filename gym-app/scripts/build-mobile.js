#!/usr/bin/env node
'use strict';

// Copies the web app into www/ for Capacitor and points it at the live server.
//
//   API_URL=https://book.yourshop.com npm run mobile:build
//
// Without API_URL the app asks for the server address on first launch, which is
// handy for testing one build against several shops.

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const src = path.join(root, 'public');
const out = path.join(root, 'www');
const apiBase = String(process.env.API_URL || '').trim().replace(/\/+$/, '');

if (apiBase && !/^https?:\/\//.test(apiBase)) {
  console.error(`API_URL must start with https:// (got "${apiBase}")`);
  process.exit(1);
}
if (apiBase.startsWith('http://') && !/localhost|127\.0\.0\.1|10\.0\.2\.2/.test(apiBase)) {
  console.warn('Warning: Android and iOS block plain http:// servers. Use https:// in production.');
}

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(src, out, { recursive: true });
// The service worker is for the website only; the native shell already ships every file.
fs.rmSync(path.join(out, 'sw.js'), { force: true });
fs.writeFileSync(path.join(out, 'config.js'),
  `// Generated by scripts/build-mobile.js\nwindow.APP_CONFIG = { apiBase: ${JSON.stringify(apiBase)}, native: true };\n`);

// The website gets its manifest and icon from the server; inside the app they are not needed.
for (const page of ['index.html', 'admin.html']) {
  const file = path.join(out, page);
  const html = fs.readFileSync(file, 'utf8')
    .replace(/\s*<link rel="manifest"[^>]*>/, '')
    .replace(/\s*<link rel="(apple-touch-)?icon"[^>]*>/g, '');
  fs.writeFileSync(file, html);
}

console.log(`www/ ready${apiBase ? ` · server ${apiBase}` : ' · server will be asked on first launch'}`);
